// Command contractgen projects the Go declarations that the API contract owns onto the
// frontend.
//
// Two modules are generated, both committed so `cd web && pnpm build` never needs a Go
// toolchain:
//
//   - web/src/lib/auth/capabilities.generated.ts, from the authorization catalog
//   - web/src/lib/api/contract.generated.ts, from the identity role/status/action catalogs
//
// The Go side is the single source of truth because it is the actual authorization
// boundary and the wire vocabulary; the frontend only mirrors it for routing, UI and
// response validation. main_test.go fails when either module drifts.
package main

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"

	"main/internal/authorization"
	"main/internal/identity"
)

const (
	capabilitiesRelativePath = "web/src/lib/auth/capabilities.generated.ts"
	contractRelativePath     = "web/src/lib/api/contract.generated.ts"
)

// generatedFile is one output module, addressed relative to the repository root so the
// generator works regardless of the caller's working directory.
type generatedFile struct {
	relativePath string
	payload      []byte
}

//go:generate go run .

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "generate frontend contract: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := repositoryRoot()
	if err != nil {
		return err
	}

	files, err := renderAll()
	if err != nil {
		return err
	}

	for _, file := range files {
		path := filepath.Join(root, filepath.FromSlash(file.relativePath))
		// 0o600 is enough: git only records the executable bit, and the file must not
		// be world-writable while it is regenerated.
		if writeErr := os.WriteFile(path, file.payload, 0o600); writeErr != nil {
			return fmt.Errorf("write %s: %w", path, writeErr)
		}
		fmt.Printf("generated %s\n", path)
	}

	return nil
}

// renderAll builds both modules. It must stay deterministic: main_test.go compares the
// output byte for byte against the committed files.
func renderAll() ([]generatedFile, error) {
	capabilities, err := renderCapabilities(authorization.All())
	if err != nil {
		return nil, err
	}

	contract, err := renderContract(identity.Roles(), identity.Statuses(), identity.AllManagedUserActions())
	if err != nil {
		return nil, err
	}

	return []generatedFile{
		{relativePath: capabilitiesRelativePath, payload: capabilities},
		{relativePath: contractRelativePath, payload: contract},
	}, nil
}

func renderCapabilities(capabilities []authorization.Capability) ([]byte, error) {
	if len(capabilities) == 0 {
		return nil, errors.New("capability catalog is empty")
	}

	values := make([]string, len(capabilities))
	names := make([]string, len(capabilities))
	seen := make(map[string]string, len(capabilities))
	for index, capability := range capabilities {
		value := string(capability)
		name, err := tsIdentifier(value)
		if err != nil {
			return nil, err
		}
		if previous, duplicate := seen[name]; duplicate {
			return nil, fmt.Errorf("capabilities %q and %q both map to the identifier %q", previous, value, name)
		}
		seen[name] = value
		values[index] = value
		names[index] = name
	}

	var builder strings.Builder
	builder.WriteString("// Code generated by internal/contractgen. DO NOT EDIT.\n")
	builder.WriteString("// Regenerate with: go generate ./internal/contractgen\n")
	builder.WriteString("//\n")
	builder.WriteString("// The Go capability catalog is the single source of truth. This module only\n")
	builder.WriteString("// mirrors it so the frontend cannot drift: every capability string, its type and\n")
	builder.WriteString("// its named handle come from the same declaration.\n\n")
	builder.WriteString("import { z } from 'zod'\n\n")

	if err := appendEnum(&builder, "capabilitySchema", values); err != nil {
		return nil, err
	}
	builder.WriteString("export type Capability = z.infer<typeof capabilitySchema>\n\n")
	if err := appendHandles(&builder, "CAPABILITY", "Capability", names, values); err != nil {
		return nil, err
	}

	return []byte(builder.String()), nil
}

func renderContract(roles []identity.Role, statuses []string, actions []identity.ManagedUserAction) ([]byte, error) {
	if len(roles) == 0 {
		return nil, errors.New("role catalog is empty")
	}
	if len(statuses) == 0 {
		return nil, errors.New("status catalog is empty")
	}
	if len(actions) == 0 {
		return nil, errors.New("managed user action catalog is empty")
	}

	roleValues := make([]string, len(roles))
	roleNames := make([]string, len(roles))
	seen := make(map[string]string, len(roles))
	for index, role := range roles {
		name, err := tsIdentifier(role.Key)
		if err != nil {
			return nil, err
		}
		if previous, duplicate := seen[name]; duplicate {
			return nil, fmt.Errorf("roles %q and %q both map to the identifier %q", previous, role.Key, name)
		}
		seen[name] = role.Key
		roleValues[index] = role.Key
		roleNames[index] = name
	}

	actionValues := make([]string, len(actions))
	for index, action := range actions {
		actionValues[index] = string(action)
	}

	var builder strings.Builder
	builder.WriteString("// Code generated by internal/contractgen. DO NOT EDIT.\n")
	builder.WriteString("// Regenerate with: go generate ./internal/contractgen\n")
	builder.WriteString("//\n")
	builder.WriteString("// The Go identity catalogs are the single source of truth for the wire vocabulary.\n")
	builder.WriteString("// This module only mirrors them: a role missing from roleKeySchema makes\n")
	builder.WriteString("// /api/auth/me fail zod parsing and silently logs the user out, so the mirror must\n")
	builder.WriteString("// never be hand-maintained.\n\n")
	builder.WriteString("import { z } from 'zod'\n\n")

	if err := appendEnum(&builder, "roleKeySchema", roleValues); err != nil {
		return nil, err
	}
	builder.WriteString("export type RoleKey = z.infer<typeof roleKeySchema>\n\n")
	if err := appendHandles(&builder, "ROLE_KEY", "RoleKey", roleNames, roleValues); err != nil {
		return nil, err
	}
	builder.WriteString("\n")
	if err := appendEnum(&builder, "userStatusSchema", statuses); err != nil {
		return nil, err
	}
	builder.WriteString("export type UserStatus = z.infer<typeof userStatusSchema>\n\n")
	if err := appendEnum(&builder, "managedUserActionSchema", actionValues); err != nil {
		return nil, err
	}
	builder.WriteString("export type ManagedUserAction = z.infer<typeof managedUserActionSchema>\n")

	return []byte(builder.String()), nil
}

// appendEnum writes a zod enum whose members come from the Go declaration, in order.
func appendEnum(builder *strings.Builder, constName string, values []string) error {
	literals := make([]string, len(values))
	for index, value := range values {
		literal, err := tsStringLiteral(value)
		if err != nil {
			return err
		}
		literals[index] = literal
	}

	fmt.Fprintf(builder, "export const %s = z.enum([\n", constName)
	for _, literal := range literals {
		fmt.Fprintf(builder, "  %s,\n", literal)
	}
	builder.WriteString("])\n\n")

	return nil
}

// appendHandles writes the named handles next to an enum: TypeScript identifier to wire
// value.
//
// Only capabilities and roles get handles. Capability strings are long and dotted, so a
// derived handle is the only readable way to reference one; statuses and actions get none
// because a typo in a bare literal is already a type error against the generated union.
// Do not "complete" the pattern by generating USER_STATUS / MANAGED_USER_ACTION: that adds
// a second spelling at every call site and buys nothing.
func appendHandles(builder *strings.Builder, constName string, typeName string, names []string, values []string) error {
	literals := make([]string, len(values))
	for index, value := range values {
		literal, err := tsStringLiteral(value)
		if err != nil {
			return err
		}
		literals[index] = literal
	}

	fmt.Fprintf(builder, "export const %s = {\n", constName)
	for index, name := range names {
		fmt.Fprintf(builder, "  %s: %s,\n", name, literals[index])
	}
	fmt.Fprintf(builder, "} as const satisfies Record<string, %s>\n", typeName)

	return nil
}

// tsStringLiteral validates value and returns it as a single-quoted literal.
//
// The generated modules are compared byte for byte, so a value that would need escaping
// is rejected instead of silently emitting a different shape.
func tsStringLiteral(value string) (string, error) {
	if value == "" {
		return "", errors.New("empty string literal")
	}
	if strings.ContainsAny(value, "'\\\"\n\r") {
		return "", fmt.Errorf("%q cannot be written as a TypeScript string literal", value)
	}

	return "'" + value + "'", nil
}

// tsIdentifier turns "management.system_logs.read" into "managementSystemLogsRead".
// The mapping is fixed so the generated object keeps stable, greppable names.
func tsIdentifier(value string) (string, error) {
	if strings.Contains(value, "\n") || strings.Contains(value, "\r") {
		return "", fmt.Errorf("%q must be a single line", value)
	}

	segments := strings.FieldsFunc(value, func(r rune) bool {
		return r == '.' || r == '_' || r == '-' || r == ' '
	})
	if len(segments) == 0 {
		return "", fmt.Errorf("%q has no identifier segments", value)
	}

	var builder strings.Builder
	for index, segment := range segments {
		lowered := strings.ToLower(segment)
		if index == 0 {
			builder.WriteString(lowered)
			continue
		}
		builder.WriteString(strings.ToUpper(lowered[:1]))
		builder.WriteString(lowered[1:])
	}

	name := builder.String()
	if name == "" || name[0] < 'a' || name[0] > 'z' {
		return "", fmt.Errorf("%q maps to the invalid TypeScript identifier %q", value, name)
	}
	for _, r := range name {
		if (r < 'a' || r > 'z') && (r < 'A' || r > 'Z') && (r < '0' || r > '9') {
			return "", fmt.Errorf("%q maps to the invalid TypeScript identifier %q", value, name)
		}
	}

	return name, nil
}

// repositoryRoot resolves the repository root from this file's location so the generator
// works regardless of the caller's working directory.
func repositoryRoot() (string, error) {
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		return "", errors.New("cannot resolve generator source path")
	}

	// <root>/internal/contractgen/main.go -> <root>
	return filepath.Join(filepath.Dir(thisFile), "..", ".."), nil
}
